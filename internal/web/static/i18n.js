const browserLang = (navigator.language || "en").toLowerCase().startsWith("de") ? "de" : "en";
export let lang = browserLang;
let dict = strings[lang];

// setLanguage switches between "auto" (browser language), "en" and "de".
export function setLanguage(pref) {
  lang = pref === "en" || pref === "de" ? pref : browserLang;
  dict = strings[lang];
  applyI18n();
}

export function t(key, vars = {}) {
  const s = dict[key] ?? strings.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}

export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll("[data-i18n-label]")) el.setAttribute("aria-label", t(el.dataset.i18nLabel));
  for (const el of root.querySelectorAll("[data-i18n-title]")) {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute("aria-label", el.title);
  }
}
